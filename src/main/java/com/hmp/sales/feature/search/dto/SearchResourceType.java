/**
 * Phân loại loại tài nguyên phục vụ việc lập chỉ mục gợi ý tìm kiếm.
 */
public enum SearchResourceType {
    /**
     * Sản phẩm tôn lợp mái và phụ kiện.
     */
    PRODUCT,

    /**
     * Danh mục sản phẩm (cây danh mục tôn, máng xối...).
     */
    CATEGORY,

    /**
     * Thương hiệu sản xuất (Hoa Sen, Đông Á, Nam Kim...).
     */
    BRAND
}

